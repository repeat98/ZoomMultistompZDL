#!/usr/bin/env python3
"""Build Loop: a looper for stock firmware, with a live screen (MS-70CDR 2.10), on zvis.

The screen's fixed parts (frame lines, knob labels and dial outlines) are one
background frame; the state words, time digits and tags are column sprites for
the top two block rows, OR-ed in by loop.c.
"""
import sys
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "common"))
from zvis_build import Canvas, raw, c_bytes, dials, encode_zoom_rle, build  # noqa: E402

WORDS = ["READY", "REC", "PLAY", "DUB", "STOP"]       # loop.c's enum order
GLYPHS = "0123456789.S"
GW = 7                                                  # scale-2 glyph advance
TAGS = [("UNDO", 0), ("LONG", 6), ("NO LONG", 6), ("CLEAR", 6)]     # (text, row)
TAG_X = 46


def background(title=False):
    c = Canvas()
    c.hline(0, 127, 11)
    c.hline(0, 127, 35)
    dials(c, ("LOOP", "DRY", "FADE"))
    if title:
        c.draw_text("LOOP", 1, 0, scale=2)
        c.draw_text("PRESS TO REC", 128 - 12 * 4, 21)
    return c


def cols2(text, scale, row=0):
    """Text as 2 bytes a column (block rows 0 and 1), and its width."""
    c = Canvas()
    c.draw_text(text, 0, row, scale=scale)
    r = raw(c)
    w = len(text) * (3 * scale + 1) - 1
    return b"".join(bytes([r[x], r[128 + x]]) for x in range(w)), w


def table(name, items):
    data, at, ws = b"", [], []
    for blob, w in items:
        at.append(len(data)); ws.append(w); data += blob
    return (c_bytes(name, data)
            + f"static const unsigned short {name}_AT[{len(at)}] = {{{', '.join(map(str, at))}}};\n"
            + f"static const unsigned char {name}_W[{len(ws)}] = {{{', '.join(map(str, ws))}}};\n")


glyphs = b""
for ch in GLYPHS:
    blob, w = cols2(ch, 2)
    glyphs += blob + bytes(2 * (GW - w))                  # pad each glyph to GW columns
words = table("LOOP_WORD", [cols2(w, 2) for w in WORDS]).replace("LOOP_WORD[", "LOOP_WORDS[").replace("LOOP_WORD_AT", "LOOP_WORD_AT")
tags = table("LOOP_TAG", [cols2(t, 1, row) for t, row in TAGS]).replace("LOOP_TAG[", "LOOP_TAGS[")
(HERE / "loop_art.h").write_text(
    "/* generated by build.py */\n"
    f"#define LOOP_GW {GW}\n#define LOOP_TAG_X {TAG_X}\n"
    + c_bytes("LOOP_BG", raw(background())) + c_bytes("LOOP_GLYPHS", glyphs) + words + tags)
build(HERE, encode_zoom_rle(background(title=True)))
