#!/usr/bin/env python3
"""Build Spectrum: a live spectrum analyzer on the pedal screen (MS-70CDR 2.10), on zvis.

Tables for spectrum.c: a cosine over the full circle (window, FFT twiddles,
the real-FFT split), and the map from 126 log-spaced screen columns
(40 Hz - 16 kHz) to the 1024-point FFT's bins: wide columns take the loudest
bin they cover, narrow (bass) columns interpolate between two bins.
"""
import math
import sys
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "common"))
from zvis_build import Canvas, raw, c_bytes, dials, fill, encode_zoom_rle, build  # noqa: E402

N = 1024
SR = 44100
F_LO, F_HI = 40.0, 16000.0
COLS = 126                          # screen columns 1..126, inside the frame
PLOT_H = 60                         # full screen (0.02): frame rows 0..59, ticks to 62, no knob row
TICKS = {100: 3, 1000: 3, 10000: 3, 50: 1, 200: 1, 500: 1, 2000: 1, 5000: 1}


def col_freq(c):
    return F_LO * (F_HI / F_LO) ** (c / (COLS - 1))


def x_of(f):
    return 1 + round((COLS - 1) * math.log(f / F_LO) / math.log(F_HI / F_LO))


def background(title=False):
    c = Canvas()
    c.rect(0, 0, 127, PLOT_H - 1)
    for f, n in TICKS.items():
        c.vline(x_of(f), PLOT_H, PLOT_H - 1 + n)
    if title:
        for x in range(1, 127):                           # a sample spectrum for the cover
            f = col_freq(x - 1)
            lvl = 0.75 - 0.18 * abs(math.log2(f / 220)) ** 1.1 + 0.08 * math.sin(x * 0.9)
            top = PLOT_H - 2 - max(0, round(lvl * (PLOT_H - 3)))
            if x % 2 == 0:
                c.vline(x, top, PLOT_H - 2)
        fill(c, 29, 7, 98, 21, 0)                          # a clear box for the title
        c.draw_text("SPECTRUM", 64 - 31, 10, scale=2)
    return c


df = SR / N
b0s, ns, fr, octs = [], [], [], []
for c in range(COLS):
    f = col_freq(c)
    lo = math.sqrt(f * col_freq(c - 1)) if c else f / (F_HI / F_LO) ** (0.5 / (COLS - 1))
    hi = math.sqrt(f * col_freq(c + 1)) if c < COLS - 1 else f * (F_HI / F_LO) ** (0.5 / (COLS - 1))
    a, b = math.ceil(lo / df), math.floor(hi / df)
    if b - a + 1 >= 2:
        b0s.append(a); ns.append(b - a + 1); fr.append(0)
    else:
        i = int(f / df)
        b0s.append(i); ns.append(0); fr.append(round((f / df - i) * 255))
    octs.append(math.log2(f / 1000))
assert max(b0s[i] + max(ns[i], 2) for i in range(COLS)) <= N // 2
cos = [math.cos(2 * math.pi * k / N) for k in range(N)]


def floats(name, vals):
    return f"static const float {name}[{len(vals)}] = {{" + ",".join(format(v, ".9e") + "f" for v in vals) + "};\n"


(HERE / "spectrum_art.h").write_text(
    "/* generated by build.py */\n"
    f"#define SPEC_N {N}u\n#define SPEC_COLS {COLS}u\n#define SPEC_PLOT_H {PLOT_H}\n"
    + floats("SPEC_COS", cos) + floats("SPEC_OCT", octs)
    + f"static const unsigned short SPEC_B0[{COLS}] = {{{','.join(map(str, b0s))}}};\n"
    + c_bytes("SPEC_NB", bytes(ns)) + c_bytes("SPEC_FR", bytes(fr))
    + c_bytes("SPEC_BG", raw(background())))
build(HERE, encode_zoom_rle(background(title=True)))
