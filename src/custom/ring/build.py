#!/usr/bin/env python3
"""Build Ring: a rotating ring oscilloscope on the pedal screen (MS-70CDR 2.10), on zvis."""
import math
import sys
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "common"))
from zvis_build import Canvas, raw, c_bytes, dials, fill, encode_zoom_rle, build  # noqa: E402

PANEL = 63                        # full screen (0.02): black panel rows 0..63, no knob row


def background(title=False):
    c = Canvas()
    fill(c, 0, 0, 127, PANEL)
    if title:
        for y in range(25, 38):
            for x in range(40, 89):
                c.px(x, y, 0)
        c.draw_text("RING", 64 - 15, 27, scale=2)
    return c


cos = [round(16384 * math.cos(2 * math.pi * k / 256)) for k in range(256)]
(HERE / "ring_art.h").write_text(
    "/* generated by build.py */\n#define RING_PANEL %d\n" % PANEL
    + c_bytes("RING_BG", raw(background()))
    + "static const short RING_COS[256] = {\n" + ",\n".join(", ".join(str(v) for v in cos[i:i + 16]) for i in range(0, 256, 16)) + "\n};\n")
build(HERE, encode_zoom_rle(background(title=True)))
