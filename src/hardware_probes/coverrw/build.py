#!/usr/bin/env python3
"""Build the CoverRW probe (test C, docs/pedal-research/animated-covers.md) into dist/CoverRW.ZDL.

The cover has a band (raw column bytes 0xFE/0xFD alternating, blank on both
sides) that the RLE stores as consecutive literal bytes. This script finds
where they land in the blob and checks that inverting them changes nothing else
(same length, same bytes elsewhere), then writes coverrw_layout.h for the C code.
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(ROOT / "build"))
sys.path.insert(0, str(ROOT / "src" / "airwindows" / "common"))

from linker import LinkerConfig, ObjFile, link, params_from_manifest  # noqa: E402
from screen_image import Canvas, encode_zoom_rle  # noqa: E402
from zdl_size_guard import check as size_check  # noqa: E402

TI_ROOT = Path("/Applications/ti/ti-cgt-c6000_8.5.0.LTS")
CFLAGS = ["--c99", "--opt_level=2", "-mv6740", "--abi=eabi", "--mem_model:data=far", f"--include_path={TI_ROOT}/include"]
BLOCK, X0, X1 = 3, 24, 103          # row-block 3 = pixel rows 24-31; stripe columns X0..X1


def cover(flipped=False):
    c = Canvas()
    c.rect(0, 0, 127, 63)
    c.draw_text('TEST C', 4, 4, scale=2)
    for x in range(X0, X1 + 1):
        # FE/FD: a nearly solid black band (one pixel row missing per column),
        # inverting to 01/02, a nearly white band; neighbours always differ.
        byte = (0xFE if (x - X0) % 2 == 0 else 0xFD) ^ (0xFF if flipped else 0)
        for z in range(8):
            c.px(x, BLOCK * 8 + z, (byte >> z) & 1)
    return c


def main() -> None:
    a, b = encode_zoom_rle(cover(False)), encode_zoom_rle(cover(True))
    assert len(a) == len(b), 'inverting the stripes changed the RLE length'
    diff = [i for i in range(len(a)) if a[i] != b[i]]
    assert diff and diff == list(range(diff[0], diff[0] + len(diff))) and len(diff) == X1 - X0 + 1, diff
    assert all(a[i] ^ b[i] == 0xFF for i in diff)
    (HERE / "coverrw_layout.h").write_text(
        f"/* generated by build.py */\n#define COVER_FLIP_OFF {diff[0]}u\n#define COVER_FLIP_LEN {len(diff)}u\n")

    m = json.loads((HERE / "manifest.json").read_text())
    obj = HERE / "coverrw.obj"
    subprocess.run([str(TI_ROOT / "bin/cl6x"), *CFLAGS, "-c", str(HERE / "coverrw.c"), f"--output_file={obj}"],
                   check=True, cwd=HERE)
    for junk in ("compiler.opt", "linker.cmd"):
        (HERE / junk).unlink(missing_ok=True)
    o = ObjFile(obj)
    externals = {s['name'] for s in o.symbols if s['name'] and s['shndx'] == 0}
    assert externals <= {f"_{m['audio_func_name']}_Pic"}, f'unexpected externals {externals}'
    for sec in o.sections:
        if sec['name'] in ('.bss', '.far', '.fardata') or sec['name'].startswith('.switch'):
            assert sec['size'] == 0, f"unexpected writable data in {sec['name']}"
    out = ROOT / "dist" / f"{m['effect_name']}.ZDL"
    link(LinkerConfig(effect_name=m["effect_name"], audio_func_name=m["audio_func_name"], gid=m["gid"], fxid=m["fxid"],
                      params=params_from_manifest(m["params"]), obj_path=obj, output_path=out, screen_image=a,
                      fxid_version=m["fxid_version"].encode(), flags_byte=m["flags_byte"], materialize_init=True,
                      use_object_edit_handlers=False, synthesize_linesel_edit_handlers=True, synth_edit_start_index=2,
                      knob3_blob_path=str(HERE / "unused")))
    size_check(out)
    data = out.read_bytes()
    assert data.count(a) == 1, 'cover not found once in the linked file'
    print(f"[coverrw] -> {out}  (stripes: {len(diff)} literal bytes at blob offset {diff[0]}, "
          f"file offset {data.index(a) + diff[0]})")


if __name__ == "__main__":
    main()
